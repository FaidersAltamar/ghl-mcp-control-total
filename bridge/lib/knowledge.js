// --- Conocimiento dinámico (Supabase) con fallback al estático ---
// Permite actualizar la base de conocimiento sin redeploy:
// se lee de la tabla public.bot_knowledge (Supabase) y se cachea 5 min.
const SUPABASE_URL = () => process.env.SUPABASE_URL;
const SUPABASE_ANON_KEY = () => process.env.SUPABASE_ANON_KEY;
const KNOWLEDGE_KEY = process.env.KNOWLEDGE_KEY || 'faiders';
const TTL = 5 * 60 * 1000; // 5 minutos

let cache = { value: null, ts: 0 };

export async function getKnowledge() {
  const now = Date.now();
  if (cache.value && now - cache.ts < TTL) return cache.value;

  const url = SUPABASE_URL();
  const anonKey = SUPABASE_ANON_KEY();
  if (url && anonKey) {
    try {
      const resp = await fetch(`${url}/rest/v1/bot_knowledge?key=eq.${KNOWLEDGE_KEY}&select=content`, {
        headers: { apikey: anonKey, Authorization: `Bearer ${anonKey}` },
      });
      if (resp.ok) {
        const rows = await resp.json();
        if (rows && rows[0] && rows[0].content) {
          cache = { value: rows[0].content, ts: now };
          return cache.value;
        }
      }
    } catch (e) {
      // fallback al estático
    }
  }
  return KNOWLEDGE;
}
